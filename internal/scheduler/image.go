// SaveTerminalImage persists image bytes in the member home the target
// container mounts and returns the absolute path visible from that container.
// An empty run ID targets the caller's live environment terminal, whose
// captured HOME is used; a run target must still have a live supervised
// container.
func (s *Scheduler) SaveTerminalImage(ctx context.Context, actor domain.MemberID, runID domain.RunID, extension string, data []byte) (string, error) {
	return s.saveTerminalUpload(ctx, actor, runID, func(account domain.MemberID) (string, error) {
		return s.cfg.Homes.SaveImage(account, extension, data)
	})
}

// SaveTerminalFile is SaveTerminalImage for any other file, kept under its
// sanitised original name.
func (s *Scheduler) SaveTerminalFile(ctx context.Context, actor domain.MemberID, runID domain.RunID, name string, data []byte) (string, error) {
	return s.saveTerminalUpload(ctx, actor, runID, func(account domain.MemberID) (string, error) {
		return s.cfg.Homes.SaveFile(account, name, data)
	})
}

func (s *Scheduler) saveTerminalUpload(ctx context.Context, actor domain.MemberID, runID domain.RunID, save func(domain.MemberID) (string, error)) (string, error) {
	if s.cfg.Homes == nil {
		return "", errors.New("scheduler: member homes are not configured")
	}

	account := actor
	var home string
	var stillLive func() bool
	if runID != "" {
		if _, err := s.cfg.Store.GetRun(ctx, runID); err != nil {
			return "", fmt.Errorf("scheduler: get upload target session: %w", err)
		}
		s.mu.Lock()
		entry := s.runs[runID]
		if entry != nil {
			account = entry.memberID
			home = entry.home
			containerID := entry.containerID
			stillLive = func() bool {
				s.mu.Lock()
				defer s.mu.Unlock()
				current := s.runs[runID]
				return current == entry && current.containerID == containerID && current.home == home
			}
		}
		s.mu.Unlock()
		if entry == nil {
			return "", errors.New("scheduler: upload target session has no live container")
		}
		if home == "" {
			return "", errors.New("scheduler: upload target session has no captured HOME")
		}
	} else {
		var running bool
		s.mu.Lock()
		entry := s.terminals[account]
		if entry != nil && !entry.cleanupPending {
			home = entry.home
			containerID := entry.containerID
			running = true
			stillLive = func() bool {
				s.mu.Lock()
				defer s.mu.Unlock()
				current := s.terminals[account]
				return current == entry && !current.cleanupPending && current.containerID == containerID && current.home == home
			}
		}
		s.mu.Unlock()
		if !running {
			return "", errors.New("scheduler: upload target environment terminal is not running")
		}
		if home == "" {
			return "", errors.New("scheduler: upload target terminal has no captured HOME")
		}
	}

	relative, err := save(account)
	if err != nil {
		return "", fmt.Errorf("scheduler: persist terminal upload: %w", err)
	}
	if stillLive != nil && !stillLive() {
		return "", errors.New("scheduler: upload target container changed while saving")
	}
	return path.Join(home, relative), nil
}

// ValidateAttachment accepts only an existing image or file generated by
// SaveTerminalImage or SaveTerminalFile in the home the run's container
// mounts. The incoming reference is the container-visible absolute path
// returned by those methods; it is never interpreted as an arbitrary host path.
func (s *Scheduler) ValidateAttachment(ctx context.Context, runID domain.RunID, reference string) error {
	if s.cfg.Homes == nil {
		return errors.New("scheduler: member homes are not configured")
	}
	if runID == "" || reference == "" || strings.ContainsAny(reference, "\x00\r\n\\") {
		return errors.New("scheduler: invalid attachment reference")
	}
	if _, err := s.cfg.Store.GetRun(ctx, runID); err != nil {
		return fmt.Errorf("scheduler: resolve attachment session: %w", err)
	}
	s.mu.Lock()
	entry := s.runs[runID]
	var account domain.MemberID
	home := ""
	if entry != nil {
		account = entry.memberID
		home = entry.home
	}
	s.mu.Unlock()
	if entry == nil || home == "" || !path.IsAbs(home) || !path.IsAbs(reference) {
		return errors.New("scheduler: attachment session has no valid captured HOME")
	}
	if name, ok := strings.CutPrefix(reference, path.Join(home, ".aether", "terminal-files")+"/"); ok {
		if !memberhome.ValidFileName(name) {
			return errors.New("scheduler: attached file reference was not server generated")
		}
		if _, _, err := s.cfg.Homes.StatFile(account, name); err != nil {
			return fmt.Errorf("scheduler: stat attached file: %w", err)
		}
		return nil
	}
	name, ok := strings.CutPrefix(reference, path.Join(home, ".aether", "terminal-images")+"/")
	if !ok {
		return errors.New("scheduler: attachment is outside the session home upload directories")
	}
	if !memberhome.ValidImageName(name) {
		return errors.New("scheduler: terminal image reference was not server generated")
	}
	if _, _, err := s.cfg.Homes.ReadImage(account, name); err != nil {
		return fmt.Errorf("scheduler: read terminal image: %w", err)
	}
	return nil
}

// ReadImage resolves a saved image reference using the run's durable home
// ownership, not a live container or a caller-selected host path. The
// container-visible HOME prefix is metadata only; new references are admitted
// separately by ValidateAttachment while that HOME is still captured.
func (s *Scheduler) ReadImage(ctx context.Context, runID domain.RunID, reference string) ([]byte, string, error) {
	if s.cfg.Homes == nil {
		return nil, "", errors.New("scheduler: member homes are not configured")
	}
	if runID == "" || !cleanReference(reference) {
		return nil, "", errors.New("scheduler: invalid terminal image reference")
	}
	name := path.Base(reference)
	if !memberhome.ValidImageName(name) || !strings.HasSuffix(path.Dir(reference), "/.aether/terminal-images") {
		return nil, "", errors.New("scheduler: terminal image reference was not server generated")
	}
	run, err := s.cfg.Store.GetRun(ctx, runID)
	if err != nil {
		return nil, "", fmt.Errorf("scheduler: resolve terminal image session: %w", err)
	}
	data, mimeType, err := s.cfg.Homes.ReadImage(run.HomeMember(), name)
	if err != nil {
		return nil, "", fmt.Errorf("scheduler: read terminal image: %w", err)
	}
	return data, mimeType, nil
}

// StatAttachedFile is ReadImage for a reference SaveTerminalFile returned:
// it reports the file's size and sniffed MIME type, not its bytes.
func (s *Scheduler) StatAttachedFile(ctx context.Context, runID domain.RunID, reference string) (int64, string, error) {
	if s.cfg.Homes == nil {
		return 0, "", errors.New("scheduler: member homes are not configured")
	}
	name, ok := attachedFileName(reference)
	if runID == "" || !ok {
		return 0, "", errors.New("scheduler: attached file reference was not server generated")
	}
	run, err := s.cfg.Store.GetRun(ctx, runID)
	if err != nil {
		return 0, "", fmt.Errorf("scheduler: resolve attached file session: %w", err)
	}
	size, mimeType, err := s.cfg.Homes.StatFile(run.HomeMember(), name)
	if err != nil {
		return 0, "", fmt.Errorf("scheduler: stat attached file: %w", err)
	}
	return size, mimeType, nil
}

// attachedFileName returns the name below the terminal file directory when
// reference has the shape SaveTerminalFile returns.
func attachedFileName(reference string) (string, bool) {
	if !cleanReference(reference) {
		return "", false
	}
	dir := path.Dir(reference)
	name := path.Base(dir) + "/" + path.Base(reference)
	return name, strings.HasSuffix(path.Dir(dir), "/.aether/terminal-files") && memberhome.ValidFileName(name)
}

func cleanReference(reference string) bool {
	return path.IsAbs(reference) && path.Clean(reference) == reference && !strings.ContainsAny(reference, "\x00\r\n\\")
}
